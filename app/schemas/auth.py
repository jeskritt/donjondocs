"""
AI Helper Docstring
Purpose: Pydantic definitions strictly filtering request bodies generated by `/login` routes and returning predictable Token structures.
Interactions:
- `app.api.auth_routes.py`: Casts payloads into these instances to ensure fast failure on malformed json.
"""

"""Authentication request/response schemas."""

from pydantic import BaseModel, EmailStr, Field


class LoginRequest(BaseModel):
    """Login credentials."""

    email: EmailStr
    password: str = Field(..., min_length=1)


class RegisterRequest(BaseModel):
    """New user registration data."""

    username: str = Field(..., min_length=3, max_length=50, pattern=r"^[a-zA-Z0-9_-]+$")
    email: EmailStr
    password: str = Field(..., min_length=8, max_length=128)


class TokenPayload(BaseModel):
    """Decoded JWT token payload."""

    sub: str  # User ID
    role: str
    exp: int | None = None
